"""Encode a photograph for the ESP32 panel's LVGL RGB565 framebuffer."""
import argparse
from pathlib import Path

from PIL import Image, ImageOps


def write_photo(source: Path) -> None:
    width, height = 240, 160
    with Image.open(source) as original:
        photo = ImageOps.exif_transpose(original).convert("RGB")
        photo = ImageOps.pad(photo, (width, height), method=Image.Resampling.LANCZOS,
                             color="black")

    data = photo.tobytes()
    pixels = []
    for index in range(0, len(data), 3):
        red, green, blue = data[index:index + 3]
        rgb565 = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
        pixels.append(f"0x{rgb565:04x}")

    lines = [
        "/* Generated by tools/make_splash_photo.py from the supplied motorcycle photo. */",
        "#include <lvgl.h>",
        "#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP",
        '#error "The splash photo requires native RGB565"',
        "#endif",
        "static const LV_ATTRIBUTE_MEM_ALIGN uint16_t pixels[] = {",
    ]
    for index in range(0, len(pixels), 12):
        lines.append("    " + ", ".join(pixels[index:index + 12]) + ",")
    lines.extend([
        "};",
        "const lv_img_dsc_t tv4_splash_motorcycle = {",
        f"    .header = {{.cf = LV_IMG_CF_TRUE_COLOR, .w = {width}, .h = {height}}},",
        "    .data_size = sizeof(pixels),",
        "    .data = (const uint8_t *)pixels,",
        "};",
    ])
    destination = Path(__file__).resolve().parents[1] / "lib/PanelUI/src/tv4_splash_motorcycle.c"
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("photo", type=Path)
    write_photo(parser.parse_args().photo)
