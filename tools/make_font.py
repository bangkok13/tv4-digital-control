"""Regenerate the LVGL bitmap subset from Noto Sans Regular 2.000 (Pillow)."""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser()
parser.add_argument("ttf", type=Path)
parser.add_argument("--title", action="store_true", help="Generate the larger dashboard title font")
args = parser.parse_args()
if args.title:
    name, size = "tv4_title_23", 23
    ranges = [(c, c) for c in sorted(set(map(ord, "TV-4 Шкильнык")))]
else:
    name, size = "tv4_text_15", 15
    ranges = [(32, 126), (0x401, 0x401), (0x410, 0x44F), (0x451, 0x451), (0x2212, 0x2212)]
font = ImageFont.truetype(str(args.ttf), size)
ascent, descent = font.getmetrics()
line_height, base_line = (ascent + descent, descent) if args.title else (21, 5)
bitmap = []
descriptors = ["    {0},"]
cmaps = []
glyph = 1
for start, end in ranges:
    cmaps.append(f"    {{.range_start={start}, .range_length={end-start+1}, "
                 f".glyph_id_start={glyph}, .type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},")
    for code in range(start, end + 1):
        char = chr(code)
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right-left, bottom-top
        index = len(bitmap)
        if width and height:
            im = Image.new("L", (width, height))
            ImageDraw.Draw(im).text((-left, -top), char, anchor="ls", font=font, fill=255)
            pixels = list(im.tobytes())
            pixels.append(0)
            bitmap.extend(((pixels[k] >> 4) << 4) | (pixels[k+1] >> 4)
                          for k in range(0, width*height, 2))
        descriptors.append(f"    {{.bitmap_index={index}, .adv_w={round(font.getlength(char)*16)}, "
                           f".box_w={width}, .box_h={height}, .ofs_x={left}, .ofs_y={-bottom}}},")
        glyph += 1

lines = ["/* Generated by tools/make_font.py. Noto Sans, SIL OFL 1.1, see FONT-LICENSE.txt. */",
         '#include <lvgl.h>', 'static const uint8_t bitmap[] = {']
lines.extend("    " + ",".join(map(str, bitmap[k:k+20])) + "," for k in range(0,len(bitmap),20))
lines += ["};", "static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {", *descriptors, "};",
          "static const lv_font_fmt_txt_cmap_t maps[] = {", *cmaps, "};",
          "static lv_font_fmt_txt_glyph_cache_t cache;",
          "static const lv_font_fmt_txt_dsc_t dsc = {",
          "    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=maps,",
          f"    .cmap_num={len(ranges)}, .bpp=4, .cache=&cache", "};",
          f"const lv_font_t {name} = {{", "    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,",
          f"    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt, .line_height={line_height}, .base_line={base_line}, .dsc=&dsc", "};"]
out = Path(__file__).resolve().parents[1] / "lib/PanelUI/src" / f"{name}.c"
out.write_text("\n".join(lines)+"\n", encoding="utf-8")
